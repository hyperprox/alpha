#!/usr/bin/env bash
# install.sh replaces /etc/resolv.conf only when it points at Tailscale's MagicDNS resolver. It used to
# fire on any file containing "ts.net", including a container resolving through 1.1.1.1 that had only
# inherited a tailnet search domain. Runs install.sh's own resolv_uses_magicdns against sample files.
#
#   bash scripts/test-install-dns.sh
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# Lift just the function out of the installer: sourcing the whole file would run the install.
eval "$(sed -n '/^resolv_uses_magicdns() {/,/^}/p' "${here}/install.sh")"
declare -F resolv_uses_magicdns >/dev/null || { echo "resolv_uses_magicdns not found in install.sh"; exit 1; }

tmp="$(mktemp -d)"; trap 'rm -rf "${tmp}"' EXIT
fail=0
check() {  # check <expect: fires|quiet> <name> <resolv.conf contents>
  printf '%s\n' "$3" > "${tmp}/resolv.conf"
  local got=quiet
  resolv_uses_magicdns "${tmp}/resolv.conf" && got=fires
  if [[ "${got}" == "$1" ]]; then echo "ok    $2"; else echo "FAIL  $2 (expected $1, got ${got})"; fail=1; fi
}

check quiet "public resolver" \
'nameserver 1.1.1.1'
check quiet "public resolver with a tailnet search domain inherited from the host" \
'search tail1234.ts.net
nameserver 1.1.1.1
nameserver 8.8.8.8'
check quiet "Proxmox-generated file with a ts.net search domain" \
'# --- BEGIN PVE ---
search example-tailnet.ts.net
nameserver 1.1.1.1
# --- END PVE ---'
check quiet "a comment that mentions the MagicDNS address" \
'# was nameserver 100.100.100.100 before
nameserver 1.1.1.1'
check quiet "an address that only starts like it" \
'nameserver 100.100.100.1000'
check quiet "LAN resolver" \
'search lan
nameserver 10.0.0.1'
check quiet "empty file" \
''
check fires "MagicDNS resolver injected by Proxmox" \
'search tail1234.ts.net
nameserver 100.100.100.100'
check fires "MagicDNS resolver, Tailscale-written file" \
'# resolv.conf(5) file generated by tailscale
nameserver 100.100.100.100
nameserver fd7a:115c:a1e0::53
search tail1234.ts.net'
check fires "IPv6 MagicDNS resolver only" \
'nameserver fd7a:115c:a1e0::53'
check fires "MagicDNS second, after a public resolver" \
'nameserver 1.1.1.1
nameserver 100.100.100.100'
check fires "indented, tab-separated" \
'  nameserver	100.100.100.100'

exit "${fail}"
