// =============================================================================
//  HyperProx — local plug-in pages
//
//  Writes local-plugins/index.ts, the list of the pages in the git-ignored local-plugins/ folder (one folder
//  per plug-in, each with a plugin.ts or plugin.tsx whose default export is a LocalPluginUI). next.config.js
//  runs it before every build; `node scripts/local-plugins.js` runs it by hand (before `tsc --noEmit`).
//
//  No local-plugins/ folder: nothing is written, and '@local-plugins' resolves to lib/local-plugins-none.ts
//  (an empty list), so a public install builds exactly as before. The generated file is inside the ignored
//  folder, so it is never a local change either.
// =============================================================================

const fs = require('fs')
const path = require('path')

const ROOT = path.join(__dirname, '..')
const DIR = path.join(ROOT, 'local-plugins')
const INDEX = path.join(DIR, 'index.ts')
const NONE = path.join(ROOT, 'lib', 'local-plugins-none.ts')
const ID = /^[a-z][a-z0-9-]{1,39}$/

/** The plug-in folders that have a page, sorted. */
function findLocalPages() {
  let names = []
  try { names = fs.readdirSync(DIR, { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name).sort() }
  catch { return [] }
  return names.filter(n => ID.test(n) && ['plugin.tsx', 'plugin.ts'].some(f => fs.existsSync(path.join(DIR, n, f))))
}

/** Write local-plugins/index.ts when the folder exists; return the module '@local-plugins' should resolve to. */
function writeLocalRegistry() {
  if (!fs.existsSync(DIR)) return NONE
  const pages = findLocalPages()
  const body = [
    '// Generated by scripts/local-plugins.js at build time. Do not edit; it is rewritten on every build.',
    "import type { LocalPluginUI } from '@/lib/local-plugins-types'",
    ...pages.map((n, i) => `import p${i} from './${n}/plugin'`),
    `export const LOCAL_PLUGINS: LocalPluginUI[] = [${pages.map((_, i) => `p${i}`).join(', ')}]`,
    '',
  ].join('\n')
  let old = null
  try { old = fs.readFileSync(INDEX, 'utf8') } catch { /* first build */ }
  if (old !== body) fs.writeFileSync(INDEX, body)
  return INDEX
}

module.exports = { writeLocalRegistry, findLocalPages }

if (require.main === module) {
  const target = writeLocalRegistry()
  console.log(target === NONE ? 'No local plug-ins.' : `Local plug-ins: ${findLocalPages().join(', ') || 'none'}`)
}
